/**
 * @offscreen/cache parses process.env with z.strictObject; release Pods and
 * Docker often carry unrelated variables such as NODE_ENV. Trim before main.
 */
const allowed = new Set([
  'API_HOST',
  'API_PORT',
  'APP_ORIGIN',
  'POC_OPEN_ACCESS',
  'BETTER_AUTH_SECRET',
  'GITHUB_CLIENT_ID',
  'GITHUB_CLIENT_SECRET',
  'DATABASE_URL',
  'DB_POOL_MAX',
  'DB_CONNECT_TIMEOUT_MS',
  'DB_STATEMENT_TIMEOUT_MS',
  'DB_IDLE_TRANSACTION_TIMEOUT_MS',
  'REDIS_URL',
  'REDIS_KEY_PREFIX',
  'REDIS_CONNECT_TIMEOUT_MS',
  'REDIS_OPERATION_TIMEOUT_MS',
  'OFFSCREEN_DOCUMENT_STORE',
  'OFFSCREEN_DOCUMENT_ROOT',
  'OFFSCREEN_DEFAULT_RULE_SOURCE',
  'OFFSCREEN_DEFAULT_RULE_ROOT_HASH',
  'OFFSCREEN_DOCUMENT_S3_BUCKET',
  'OFFSCREEN_DOCUMENT_S3_REGION',
  'OFFSCREEN_DOCUMENT_S3_ENDPOINT',
  'OFFSCREEN_DOCUMENT_S3_PREFIX',
  'OFFSCREEN_DOCUMENT_S3_ACCESS_KEY_ID',
  'OFFSCREEN_DOCUMENT_S3_SECRET_ACCESS_KEY',
  'OFFSCREEN_DOCUMENT_S3_FORCE_PATH_STYLE',
  'GAME_AUTHORITY_HOST',
  'GAME_AUTHORITY_PORT',
  'GAME_AUTHORITY_SERVICE_TOKEN',
  'GAME_AUTHORITY_CONTROL_TOKEN',
  'GAME_AUTHORITY_EXECUTOR_TOKEN',
  'GAME_AUTHORITY_TIMEOUT_MS',
  'GAME_AUTHORITY_MODE',
  'GAME_AUTHORITY_ORIGIN',
  'STORYTELLER_LIVE_ENABLED',
  'STORYTELLER_EXECUTION_JSON',
  'PATH',
  'HOME',
  'HOSTNAME',
  'TZ',
]);

for (const key of Object.keys(process.env)) {
  if (!allowed.has(key)) {
    delete process.env[key];
  }
}